"""템플릿이 늘 쓰는 값 — 판 번호와 미리보기로 가는 길.

**판을 화면에 띄우는 이유**: 배포가 실제로 갈렸는지, 지금 보는 화면이 어느
판인지를 눈으로 확인할 수 있어야 한다. 오늘만 뷰어를 여섯 번 구웠고, 그중
한 번은 판 번호가 파이프라인을 끌고 가 자동 수집을 4시간 반 멈추게 했다
(devlog 026). 그런 일이 났을 때 "지금 뭐가 떠 있나" 를 묻는 데가 있어야 한다.

값은 `.env` 의 `IMAGE_TAG` 에서 온다 — compose 가 `env_file` 로 통째로 넘긴다.
배포 스크립트가 그 한 줄을 고치므로 **배포한 것과 화면에 뜨는 것이 같은 값**이다.
개발 서버처럼 그 변수가 없는 자리에서는 아무것도 안 보인다.

## 미리보기

바꾼 화면을 찍어 둔 **정지 화면 갤러리**가 80 의 `/ForGIA-preview/` 에 날짜별로
쌓여 있다(`tools/publish_preview.py`, 실제 자리는 `/srv/paleolab/ForGIA-preview/`).
거기로 가는 길이 화면에 없으면 주소를 직접 쳐야 한다 — 머리글 오른쪽 구석에
작게 낸다.

**경로를 템플릿에 박지 않는다.** 이 앱의 URL 이 아니라 nginx 가 정하는 이웃
자리라 `reverse()` 로 못 만든다 — 그래서 환경변수로 받는다. 비우면 안 보인다.

## 이 판이 어느 자리인가 (`FORGIA_ENV_LABEL`)

운영(`/ForGIA/`)과 테스트(`/ForGIATest/`)가 **같은 오리진에 같은 모양으로**
떠 있다 — 주소창 말고는 구분할 것이 없다. 판 번호도 둘이 같을 때가 많다(테스트는
내보내기 직전 판을 거는 자리라 오히려 같은 것이 정상이다). 그 상태에서 테스트
화면을 운영으로 알고 검토하면 **사본에 한 교정은 아무 데도 안 남는다.**

그래서 값이 있으면 화면 전체에 워터마크로 낸다. **비어 있는 것이 기본이고**,
켜는 것은 그 자리의 `.env` 다 — 운영 `.env` 에는 이 줄이 없다.

- **글자를 여기서 정하지 않는다.** 테스트만이 아니라 개발 서버·시연용처럼
  *"운영이 아닌 자리"* 가 여럿이라, 무엇이라 부를지는 그 자리가 정한다
- **판 번호(`IMAGE_TAG`)와 겹치지 않는다.** 그쪽은 *무엇이 떠 있나*, 이쪽은
  *어디에 떠 있나* 다. 둘 다 필요하고 실제로 함께 뜬다

### `DEBUG` 면 안 적어도 뜬다

개발 서버(`manage.py runserver`)는 **사람이 손으로 환경변수를 세우는 자리**라
빠뜨리기 쉽다. 그런데 그쪽이 오히려 위험하다 — 작업 트리의 코드로 돌고, 사내망에
열려 있고(`0.0.0.0`), 사본 DB 를 붙이라는 규약을 어기면 **운영 DB 를 직접 만진다.**

그래서 **켜는 것을 기억에 맡기지 않는다.** `DEBUG` 가 켜져 있고 이름이 없으면
`DEFAULT_DEV_LABEL` 로 뜬다. 이 갈래가 운영·테스트를 건드리지 않는 근거는
**그 둘이 `.env` 에 `FORGIA_DEBUG=0` 을 갖고 있다**는 것이다(둘 다 그렇게
적혀 있고, `DEBUG=1` 인 컨테이너를 사내망에 내보내는 것 자체가 이미 사고다).
Django 의 시험 러너는 `DEBUG` 를 끄고 돌리므로 시험에도 안 샌다.

이름을 적으면 그것이 이긴다 — 개발 서버에서 다른 이름을 쓰고 싶으면
`FORGIA_ENV_LABEL` 을 준다.
"""
import os

from django.conf import settings

# `tools/publish_preview.py` 가 내보내는 자리다. 규칙이 갈라지면 버튼이 404 로
# 간다 — 고칠 때 그 스크립트와 함께 본다.
DEFAULT_PREVIEW_URL = "/ForGIA-preview/"

# `DEBUG` 인데 이름이 없을 때 쓰는 글자. **테스트 인스턴스와 같은 말을 쓴다** —
# 여기서 갈라야 할 것은 *개발이냐 테스트냐* 가 아니라 **운영이냐 아니냐**다.
DEFAULT_DEV_LABEL = "Test Server"


def version(request):
    return {
        "image_tag": os.environ.get("IMAGE_TAG", ""),
        "preview_url": os.environ.get("FORGIA_PREVIEW_URL",
                                      DEFAULT_PREVIEW_URL).strip(),
        # **운영에서 비어 있는 것이 기본이다** — 이 값이 서면 화면을 가린다.
        # 적은 것이 이기고, 없으면 `DEBUG` 가 대신 세운다 (머리말 참고).
        "env_label": (os.environ.get("FORGIA_ENV_LABEL", "").strip()
                      or (DEFAULT_DEV_LABEL if settings.DEBUG else "")),
    }
